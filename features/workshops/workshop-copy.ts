const translations: Record<WorkshopLocale, WorkshopCopy> = {
  "en-IN": english,
  "te-IN": telugu,
  "hi-IN": hindi,
};

export function getWorkshopCopy(locale: string): {
  locale: WorkshopLocale;
  copy: WorkshopCopy;
  usesEnglishFallback: boolean;
} {
  if (locale === "te-IN" || locale === "hi-IN") {
    return { locale, copy: translations[locale], usesEnglishFallback: false };
  }
  return {
    locale: "en-IN",
    copy: english,
    usesEnglishFallback: locale !== "en-IN",
  };
}
